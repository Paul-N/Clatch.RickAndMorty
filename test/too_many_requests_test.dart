import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:rick_and_morty/dto/too_many_requests.dart';
import 'package:rick_and_morty/rest_api/api_errors.dart';


// Captured from GET https://rickandmortyapi.com/api/character/2 on 2026-10-21.

final uri = Uri.parse('https://rickandmortyapi.com/api/character/2');

final _headers = {
  'retry-after': '2',
  'content-type': 'application/json; charset=utf-8',
  'cache-control': 'private, max-age=0, no-store, no-cache, must-revalidate, post-check=0, pre-check=0',
  'expires': 'Thu, 01 Jan 1970 00:00:01 GMT',
  'referrer-policy': 'same-origin',
  'date': 'Wed, 21 Oct 2026 00:06:35 GMT',
  'x-frame-options': 'SAMEORIGIN',
  'report-to': '{"group":"cf-nel","max_age":604800,"endpoints":[{"url":"https://a.nel.cloudflare.com/report/v4?s=ZaiQHogC0hHrx8CHkAzJK0ibsfltaKakbrTtPIwHbt0WOabh%2Fc6ux%2F8R9jxxbfzgbHGfReCryUGKPPBSxL7Vi19PlGk%2Bl88U41tCVc24G0yURt8SkdMoRbtY8l95RQY4pjmrbSX7"}]}',
  'nel': '{"report_to":"cf-nel","success_fraction":0.0,"max_age":604800}',
  'expect-ct': 'max-age=86400, enforce',
  'x-content-type-options': 'nosniff',
  'x-xss-protection': '1; mode=block',
  'server-timing': 'cfExtPri',
  'priority': 'u=0,i=?0',
  'server': 'cloudflare',
  'cf-ray': 'a4dc0468db409ce0-VIE',
  'alt-svc': 'h3=":443"; ma=86400',
  'content-length': '981',
  'X-Firefox-Http3': 'h3',
};

// Raw string (r'''): the body contains \n escapes inside a JSON string, which
// a normal Dart string would turn into real newlines and make invalid JSON.
const _rawBody = r'''
{
    "type": "https://developers.cloudflare.com/support/troubleshooting/http-status-codes/cloudflare-1xxx-errors/error-1015/",
    "title": "Error 1015: You are being rate limited",
    "status": 429,
    "detail": "You are being rate-limited by the website owner's configuration.",
    "instance": "a4dc0468db409ce0",
    "error_code": 1015,
    "error_name": "rate_limited",
    "error_category": "rate_limit",
    "ray_id": "a4dc0468db409ce0",
    "timestamp": "2026-10-21T00:06:35Z",
    "zone": "rickandmortyapi.com",
    "cloudflare_error": true,
    "retryable": true,
    "retry_after": 30,
    "owner_action_required": false,
    "what_you_should_do": "**Wait and retry.** This block is transient. Wait at least 30 seconds, then retry with exponential backoff.\n\nRecommended approach:\n1. Wait 30 seconds before your next request\n2. If rate-limited again, double the wait time (60s, 120s, etc.)\n3. If rate-limiting persists after 5 retries, stop and reassess your request pattern",
    "footer": "This error was generated by Cloudflare on behalf of the website owner."
}
''';

final client = MockClient((http.Request request) async {
  if(request.url == uri) {
    return http.Response(
      _rawBody,
      429,
      headers: _headers,
    );
  } else {
    throw Exception('Unexpected request: ${request.url}');
  }
});

void main() {
  test('test DTOs', () async {
    final response = await client.get(uri);
    final error = CloudflareTooManyRequestsError.fromResponse(response);

    expect(error.statusCode, 429);
    expect(error.isRateLimited1015, isTrue);

    // Headers
    final h = error.headers;
    expect(h.retryAfter, const Duration(seconds: 2));
    expect(h.date, DateTime.utc(2026, 10, 21, 0, 6, 35));
    expect(h.server, 'cloudflare');
    expect(h.cfRay, 'a4dc0468db409ce0-VIE');
    expect(h.serverTiming, 'cfExtPri');

    expect(h.nel?.reportTo, 'cf-nel');
    expect(h.nel?.successFraction, 0.0);
    expect(h.nel?.maxAge, 604800);

    expect(h.reportTo?.group, 'cf-nel');
    expect(h.reportTo?.maxAge, 604800);
    expect(h.reportTo?.endpoints, hasLength(1));
    expect(h.reportTo?.endpoints.single.url?.host, 'a.nel.cloudflare.com');

    // RFC 9457 standard members
    final problem = error.details?.as1OrNull;
    expect(problem, isNotNull);
    expect(problem!.status, 429);
    expect(problem.title, 'Error 1015: You are being rate limited');
    expect(problem.detail, contains('rate-limited'));
    expect('${problem.type}', startsWith('https://developers.cloudflare.com/'));
    expect('${problem.instance}', 'a4dc0468db409ce0');

    // Cloudflare extension members
    expect(problem.cloudflareError, isTrue);
    expect(problem.errorCode, 1015);
    expect(problem.errorName, 'rate_limited');
    expect(problem.errorCategory, CloudflareErrorCategory.rateLimit);
    expect(problem.rayId, 'a4dc0468db409ce0');
    expect(problem.zone, 'rickandmortyapi.com');
    expect(problem.timestamp, DateTime.utc(2026, 10, 21, 0, 6, 35));
    expect(problem.retryable, isTrue);
    expect(problem.retryAfter, const Duration(seconds: 30));
    expect(problem.ownerActionRequired, isFalse);
    expect(problem.whatYouShouldDo, contains('exponential backoff'));
    expect(problem.footer, contains('generated by Cloudflare'));
  });

  test('the Retry-After header wins over the body', () async {
    final error = CloudflareTooManyRequestsError.fromResponse(await client.get(uri));

    expect(error.headers.retryAfter, const Duration(seconds: 2));
    expect(error.details?.as1OrNull?.retryAfter, const Duration(seconds: 30));
    expect(error.retryAfter(), const Duration(seconds: 2));
  });

  test('falls back to the body, then to the default', () {
    // No Retry-After header: the body's retry_after is used.
    final bodyOnly = CloudflareTooManyRequestsError.fromResponse(
      http.Response(_rawBody, 429),
    );
    expect(bodyOnly.headers.retryAfter, isNull);
    expect(bodyOnly.retryAfter(), const Duration(seconds: 30));

    // Neither: the fallback (30 s unless given).
    final nothing = CloudflareTooManyRequestsError.fromResponse(http.Response('', 429));
    expect(nothing.retryAfter(fallback: const Duration(seconds: 5)),
        const Duration(seconds: 5));
    expect(nothing.retryAfter(), const Duration(seconds: 30));
  });

  test('Retry-After in the HTTP-date form is ignored', () {
    // Only the delta-seconds form is understood. (fromHeaders expects
    // lower-case keys, which is what Response.headers provides.)
    final headers = TooManyRequestsErrorHeaders.fromHeaders(
      {'retry-after': 'Wed, 21 Oct 2026 00:06:35 GMT'},
    );
    expect(headers.retryAfter, isNull);
  });

  test('a 429 that is not from Cloudflare leaves cloudflare empty', () {
    final plain = CloudflareTooManyRequestsError.fromResponse(
      http.Response('{"error":"slow down"}', 429, headers: {'retry-after': '10'}),
    );
    expect(plain.statusCode, 429);
    expect(plain.isRateLimited1015, isFalse);
    expect(plain.details?.as1OrNull?.cloudflareError ?? false, isFalse);
    expect(plain.retryAfter(), const Duration(seconds: 10));

    final text = CloudflareTooManyRequestsError.fromResponse(
      http.Response('error code: 1015', 429),
    );
    expect(text.details?.as2OrNull, isNotNull);
    expect(text.isRateLimited1015, isFalse);
    expect(text.retryAfter(), const Duration(seconds: 30));
  });

  test('unknown categories do not break parsing', () {
    final error = CloudflareTooManyRequestsError.fromResponse(http.Response(
      '{"type":"about:blank","title":"x","status":429,"detail":"x","instance":"x",'
          '"cloudflare_error":true,"error_code":1015,"error_name":"rate_limited",'
          '"error_category":"brand_new"}',
      429,
    ));

    expect(error.details?.as1OrNull?.errorCategory, CloudflareErrorCategory.unknown);
    expect(error.isRateLimited1015, isTrue);
  });

  test('malformed NEL, Report-To and Date headers read as null', () {
    final headers = TooManyRequestsErrorHeaders.fromHeaders({
      'nel': 'not json',
      'report-to': '{oops',
      'date': 'yesterday',
    });

    expect(headers.nel, isNull);
    expect(headers.reportTo, isNull);
    expect(headers.date, isNull);
  });

  test('Report-To with several groups keeps the first', () {
    final reportTo = NelReportTo.tryParse(
      '{"group":"a","max_age":1,"endpoints":[]},'
          '{"group":"b","max_age":2,"endpoints":[]}',
    );

    expect(reportTo?.group, 'a');
    expect(reportTo?.maxAge, 1);
  });
}